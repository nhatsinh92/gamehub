export const TOKEN = "test-token-not-secret";

export const WIN: GameResult = {
  status: "SUCCESS",
  isWin: true,
  reward: { id: "r1", name: "Golden Ticket", code: "GT" },
  remainingTurns: 3,
  message: "You win",
};

export interface FakeOptions {
  config?: GameConfig;
  configError?: boolean;
  result?: GameResult;
  submitError?: boolean;
  /** when set, getConfig stays pending until this is called */
  holdConfig?: boolean;
}

export function fakeAdapter(opts: FakeOptions = {}): {
  adapter: GameAdapter;
  calls: { submitResult: number[] };
  releaseConfig(): void;
} {
  const calls = { submitResult: [] as number[] };
  let release: () => void = () => {};
  const gate = opts.holdConfig
    ? new Promise<void>((r) => {
        release = r;
      })
    : Promise.resolve();
  const err = { kind: "http" as const, message: "boom" };
  const adapter: GameAdapter = {
    getConfig: async () => {
      await gate;
      return opts.configError
        ? { ok: false, error: err }
        : { ok: true, data: opts.config ?? {} };
    },
    getCurrentUser: () => Promise.resolve({ ok: false, error: err }),
    submitResult: (_env, score) => {
      calls.submitResult.push(score);
      return Promise.resolve(
        opts.submitError
          ? { ok: false, error: err }
          : { ok: true, data: opts.result ?? WIN },
      );
    },
  };
  return { adapter, calls, releaseConfig: () => release() };
}

export async function flush(): Promise<void> {
  await act(async () => {
    await Promise.resolve();
    await Promise.resolve();
  });
}

export function renderApp(
  fake: ReturnType<typeof fakeAdapter>,
  overrides: Partial<MountOptions> = {},
): { container: HTMLElement; tracking: TrackingEvent[]; unmount(): void } {
  (
    globalThis as { IS_REACT_ACT_ENVIRONMENT?: boolean }
  ).IS_REACT_ACT_ENVIRONMENT = true;
  const tracking: TrackingEvent[] = [];
  const container = document.createElement("div");
  document.body.appendChild(container);
  const root = createRoot(container);
  void act(() => {
    root.render(
      <App
        gameId="test-game"
        adapter={fake.adapter}
        httpConfig={{ baseUrl: "https://api.test", getAccessTokenFunc: () => TOKEN }}
        sendTrackingFunc={(e) => {
          tracking.push(e);
        }}
        width={360}
        height={480}
        {...overrides}
      />,
    );
  });
  return {
    container,
    tracking,
    unmount: () => {
      void act(() => root.unmount());
      container.remove();
    },
  };
}

export function stubCanvasRect(width: number, height: number): void {
  HTMLCanvasElement.prototype.getBoundingClientRect = () =>
    ({
      x: 0,
      y: 0,
      left: 0,
      top: 0,
      right: width,
      bottom: height,
      width,
      height,
      toJSON: () => ({}),
    }) as DOMRect;
}

function fire(
  canvas: Element,
  type: string,
  x: number,
  y: number,
): void {
  const init = { clientX: x, clientY: y, bubbles: true, buttons: 1 };
  const event =
    typeof PointerEvent === "function"
      ? new PointerEvent(type, init)
      : new MouseEvent(type, init);
  canvas.dispatchEvent(event);
}

export function scratch(canvas: Element, points: [number, number][]): void {
  void act(() => {
    const [first, ...rest] = points;
    if (!first) return;
    fire(canvas, "pointerdown", first[0], first[1]);
    for (const [x, y] of rest) fire(canvas, "pointermove", x, y);
    const last = points[points.length - 1] ?? first;
    fire(canvas, "pointerup", last[0], last[1]);
  });
}

/** Covers the whole 360x480 card (stubCanvasRect(360, 480)). */
export function scratchAll(canvas: Element): void {
  const points: [number, number][] = [];
  for (let y = 0; y <= 480; y += 20) {
    for (let x = 0; x <= 360; x += 20) points.push([x, y]);
  }
  scratch(canvas, points);
}
